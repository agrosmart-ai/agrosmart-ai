import streamlit as st
import pandas as pd
import joblib
import matplotlib.pyplot as plt
from sklearn.tree import plot_tree

st.set_page_config(
    page_title="AgroSmart AI",
    page_icon="🌱",
    layout="wide"
)

@st.cache_resource
def load_model():
    return joblib.load("irrigation_model.pkl")

model = load_model()

st.markdown("""
<style>
.stApp {
    background-color: #F0F7F2;
}
h1, h2, h3 {
    color: #14532D !important;
}
[data-testid="stMetric"] {
    background-color: white;
    padding: 20px;
    border-radius: 15px;
    border: 1px solid #D1E7D7;
}
.stButton > button {
    background-color: #15803D;
    color: white;
    border-radius: 12px;
    width: 100%;
}
</style>
""", unsafe_allow_html=True)

st.title("🌱 AgroSmart AI")
st.subheader("Intelligent Irrigation & Decision Support System")
st.caption("ESP32 | IoT | Decision Tree Machine Learning")

st.divider()

a, b, c = st.columns(3)
a.metric("AI Model", "Decision Tree")
b.metric("Input Features", "3")
c.metric("Model Status", "Ready")

tab1, tab2 = st.tabs([
    "🧠 AI Prediction",
    "🌳 Model Analysis"
])

with tab1:
    st.header("Environmental Input")
    st.info("Simulation Mode — Manual sensor inputs")

    col1, col2, col3 = st.columns(3)

    with col1:
        soil = st.slider(
            "💧 Soil Moisture (%)", 0, 100, 40
        )

    with col2:
        temp = st.slider(
            "🌡️ Temperature (°C)", 15, 45, 35
        )

    with col3:
        humidity = st.slider(
            "☁️ Humidity (%)", 0, 100, 60
        )

    sample = pd.DataFrame(
        [[soil, temp, humidity]],
        columns=[
            "Soil_Moisture",
            "Temperature",
            "Humidity"
        ]
    )

    if st.button("🧠 Run AI Prediction"):
        prediction = model.predict(sample)[0]

        st.divider()
        st.header("AI Prediction Result")

        if prediction == 1:
            st.success("💧 IRRIGATION REQUIRED")
            st.metric("Recommended Pump Status", "ON")
        else:
            st.info("🌱 IRRIGATION NOT REQUIRED")
            st.metric("Recommended Pump Status", "OFF")

        st.subheader("Explainable AI — Decision Path")

        tree = model.tree_
        path = model.decision_path(sample)
        leaf = model.apply(sample)[0]

        for node in path.indices:
            if node == leaf:
                continue

            feature = tree.feature[node]
            threshold = tree.threshold[node]
            value = sample.iloc[0, feature]
            name = sample.columns[feature]
            operator = "<=" if value <= threshold else ">"

            st.write(
                f"Node {node}: {name} = {value} "
                f"{operator} {threshold:.2f}"
            )

        st.write(f"Final prediction class: {prediction}")

        st.caption(
            "Prediction generated by the trained "
            "Decision Tree model."
        )

    st.warning(
        "Simulation only. This application does not "
        "control the physical water pump."
    )

with tab2:
    st.header("Decision Tree Visualization")

    fig, ax = plt.subplots(figsize=(16, 8))

    plot_tree(
        model,
        feature_names=[
            "Soil Moisture",
            "Temperature",
            "Humidity"
        ],
        class_names=["Pump OFF", "Pump ON"],
        filled=True,
        rounded=True,
        ax=ax
    )

    st.pyplot(fig)
    plt.close(fig)

    st.subheader("AI Feature Importance")

    importance = pd.DataFrame({
        "Feature": [
            "Soil Moisture",
            "Temperature",
            "Humidity"
        ],
        "Importance": model.feature_importances_
    })

    st.bar_chart(
        importance.set_index("Feature")
    )

    st.subheader("Model Information")

    st.write("Algorithm: Decision Tree Classifier")
    st.write("Dataset: 252 synthetic samples")
    st.write("Training and testing split: 80:20")
    st.write(f"Tree depth: {model.get_depth()}")
    st.write(f"Number of leaves: {model.get_n_leaves()}")

    st.info(
        "The model was trained on synthetic data. "
        "Real-world agricultural validation is required."
    )

st.divider()
st.caption(
    "AgroSmart AI | Final Year Project | "
    "Artificial Intelligence & Internet of Things"
)
